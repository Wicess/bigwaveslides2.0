/*
 * gen-indexing-urls.ts — regenerate indexing-urls.txt: ONLY the URLs we
 * actually want indexed, mirroring the trimmed app/sitemap.ts. That means:
 *   • bilingual (/en + /fr) for the fully-translated pages (core + products/blog)
 *   • English-only for the location + use-case pages (their /fr variants render
 *     English and are noindexed), and
 *   • only the wave-1 PRIORITY cities — the other city pages are noindexed until
 *     the domain earns authority, so they're deliberately excluded here.
 *
 * Run:  npm run gen:indexing-urls
 */
import { writeFileSync } from "node:fs";
import { PrismaPg } from "@prisma/adapter-pg";
import pkg from "@prisma/client";
import { US_STATES, getPriorityCities } from "../lib/locations";
import { USE_CASES } from "../lib/use-cases";

const { PrismaClient } = pkg;
const adapter = new PrismaPg({ connectionString: process.env.DATABASE_URL });
const prisma = new PrismaClient({ adapter });

const BASE = "https://www.bigwaveslides.com";
const BOTH = ["en", "fr"] as const;
const EN = ["en"] as const;

// Fully-translated pages → indexed in both locales.
const BILINGUAL_STATIC = [
  "",
  "/about",
  "/services",
  "/shop",
  "/rent",
  "/blog",
  "/testimonials",
  "/contact",
  "/faq",
  "/privacy-policy",
  "/terms-of-service",
];
// English-only programmatic pages (their /fr twins are noindexed duplicates).
const EN_ONLY_STATIC = ["/water-slide-rentals", "/water-slides-for", "/answers"];

type Section = {
  title: string;
  paths: string[];
  locales: readonly ("en" | "fr")[];
};

async function main() {
  const [shop, rent, posts, blogCats, tags] = await Promise.all([
    prisma.product.findMany({
      where: { status: "ACTIVE", type: { in: ["SALE", "BOTH"] } },
      select: { slug: true },
      orderBy: { slug: "asc" },
    }),
    prisma.product.findMany({
      where: { status: "ACTIVE", type: { in: ["RENTAL", "BOTH"] } },
      select: { slug: true },
      orderBy: { slug: "asc" },
    }),
    prisma.blogPost.findMany({
      where: { status: "PUBLISHED" },
      select: { slug: true },
      orderBy: { slug: "asc" },
    }),
    prisma.blogCategory.findMany({
      select: { slug: true },
      orderBy: { slug: "asc" },
    }),
    prisma.tag.findMany({ select: { slug: true }, orderBy: { slug: "asc" } }),
  ]);

  const sections: Section[] = [
    { title: "MAIN PAGES (en + fr)", paths: BILINGUAL_STATIC, locales: BOTH },
    { title: "HUBS & ANSWERS (en)", paths: EN_ONLY_STATIC, locales: EN },
    {
      title: "STATES (en)",
      paths: US_STATES.map((s) => `/water-slide-rentals/${s.slug}`),
      locales: EN,
    },
    {
      title: "PRIORITY CITIES (en)",
      paths: getPriorityCities().map(
        (c) => `/water-slide-rentals/${c.state.slug}/${c.slug}`,
      ),
      locales: EN,
    },
    {
      title: "USE-CASE PAGES (en)",
      paths: USE_CASES.map((u) => `/water-slides-for/${u.slug}`),
      locales: EN,
    },
    {
      title: "SHOP PRODUCTS (en + fr)",
      paths: shop.map((p) => `/shop/${p.slug}`),
      locales: BOTH,
    },
    {
      title: "RENTALS (en + fr)",
      paths: rent.map((p) => `/rent/${p.slug}`),
      locales: BOTH,
    },
    {
      title: "BLOG POSTS (en + fr)",
      paths: posts.map((p) => `/blog/${p.slug}`),
      locales: BOTH,
    },
    {
      title: "BLOG CATEGORIES (en + fr)",
      paths: blogCats.map((c) => `/blog/category/${c.slug}`),
      locales: BOTH,
    },
    {
      title: "BLOG TAGS (en + fr)",
      paths: tags.map((t) => `/blog/tag/${t.slug}`),
      locales: BOTH,
    },
  ];

  const count = (s: Section) => s.paths.length * s.locales.length;
  const total = sections.reduce((n, s) => n + count(s), 0);

  const lines: string[] = [
    "# Big Wave Slides — URLs to submit for indexing (Google Search Console / Bing)",
    "# Auto-generated by scripts/gen-indexing-urls.ts — mirrors the TRIMMED sitemap.",
    `# Total indexable URLs: ${total}. Only pages we WANT indexed are listed:`,
    "# priority cities only, English-only for location/use-case pages. The other",
    "# city pages and French location pages are intentionally noindexed — do NOT",
    "# submit them.",
    "",
    "## FASTEST PATH — submit this ONE sitemap in GSC > Sitemaps and Bing > Sitemaps",
    `${BASE}/sitemap.xml`,
    "",
    "## PRIORITY ORDER for manual URL Inspection (do these first, top to bottom):",
    "##   1) MAIN PAGES  2) STATES  3) PRIORITY CITIES  4) USE-CASE PAGES  5) the rest",
    "",
  ];

  for (const s of sections) {
    lines.push(`## ${s.title}  (${count(s)})`);
    for (const p of s.paths)
      for (const l of s.locales) lines.push(`${BASE}/${l}${p}`);
    lines.push("");
  }

  writeFileSync("indexing-urls.txt", lines.join("\n"));
  console.log(
    `Wrote indexing-urls.txt — ${total} URLs across ${sections.length} sections.`,
  );
  for (const s of sections) console.log(`  ${s.title}: ${count(s)} URLs`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
